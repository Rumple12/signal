"""Lab 1, Section 2.2: PSNR and SSIM comparisons."""

from io import BytesIO
from pathlib import Path
from urllib.request import Request, urlopen

import matplotlib.pyplot as plt
import numpy as np
from PIL import Image
from skimage.metrics import structural_similarity


# Load the teacher's image. urllib avoids an extra requests dependency.
def load_image(url):
    request = Request(url, headers={"User-Agent": "DT081A-Lab1/1.0"})
    with urlopen(request, timeout=30) as response:
        return np.array(Image.open(BytesIO(response.read())).convert("L"))


# Teacher's simple method: keep every factor-th pixel, then repeat it.
def resample_image(image, factor):
    small = image[::factor, ::factor]
    return np.repeat(np.repeat(small, factor, axis=0), factor, axis=1)


# Teacher's requantization method: group intensities into fewer levels.
def requantize_image(image, bpp):
    levels = 2**bpp
    return np.floor(image / (256/levels)) * (256/levels)


# Apply spatial reduction first, then reduce the gray levels.
def combine_methods(image, factor, bpp):
    return requantize_image(resample_image(image, factor), bpp)


# Reduce and restore the image dimensions using bicubic interpolation.
def bicubic_resample(image, factor):
    height, width = image.shape
    small = Image.fromarray(image).resize(
        (width // factor, height // factor), Image.Resampling.BICUBIC)
    return np.array(small.resize((width, height), Image.Resampling.BICUBIC))



# Use floating-point subtraction so uint8 values do not wrap around.
def calculate_psnr(original, processed):
    error = original.astype(float) - processed.astype(float)
    mse = np.mean(error**2)
    if mse == 0:
        return float("inf")
    return 10 * np.log10(255**2 / mse)


# Compare the requested bit depths for each resampling factor.
def compare_psnr(image, factors, bit_depths):
    results = []
    for factor in factors:
        scores = []
        for bpp in bit_depths:
            processed = combine_methods(image, factor, bpp)
            scores.append(calculate_psnr(image, processed))
        results.append(scores)
    return results


image_url = "https://upload.wikimedia.org/wikipedia/en/7/7d/Lenna_%28test_image%29.png"
original = load_image(image_url)
processed_images = [resample_image(original, 4), requantize_image(original, 4),
                    combine_methods(original, 2, 4), bicubic_resample(original, 4)]
processing_names = ["Simple resampling, factor 4", "Requantization, 4 bpp",
                    "Combined factor 2, 4 bpp", "Bicubic resampling, factor 4"]

# Calculate both measures from the same original and processed images.
psnr_scores = []
ssim_scores = []
for name, processed in zip(processing_names, processed_images):
    psnr = calculate_psnr(original, processed)
    score = structural_similarity(
        original.astype(float), processed.astype(float), data_range=255)
    psnr_scores.append(psnr)
    ssim_scores.append(score)
    print(f"{name}: PSNR = {psnr:.4f} dB; SSIM = {score:.4f}")

# Confirm the prepared Q1 statement before using it in the report.
if psnr_scores[0] < psnr_scores[1]:
    print("Q1 confirmed: simple resampling has lower PSNR than requantization.")
else:
    print("Q1 does not match the calculated PSNR values.")

resampling_factors = [2, 4, 8]
bit_depths = [2, 4, 6, 8]
comparison_scores = compare_psnr(original, resampling_factors, bit_depths)
for factor, scores in zip(resampling_factors, comparison_scores):
    for bpp, score in zip(bit_depths, scores):
        print(f"Factor {factor}, {bpp} bpp: PSNR = {score:.4f} dB")

# Figure 13 is the only figure generated by this script.
figure_folder = Path(__file__).resolve().parent.parent / "figures"
figure_folder.mkdir(exist_ok=True)
plt.rcParams.update({"font.size": 11, "axes.spines.top": False,
                     "axes.spines.right": False, "lines.linewidth": 1.5})
plt.figure(figsize=(8, 4))
colours = ["#526d82", "#4c7067", "#9a6848"]
for factor, scores, colour in zip(resampling_factors, comparison_scores, colours):
    plt.plot(bit_depths, scores, "o-", color=colour, label=f"Factor {factor}")
plt.title("PSNR versus Bits per Pixel")
plt.xlabel("Bits per pixel")
plt.ylabel("PSNR (dB)")
plt.xticks(bit_depths)
plt.grid(axis="y", alpha=0.2)
plt.legend(title="Resampling")
plt.tight_layout()
plt.savefig(figure_folder / "section2_2_psnr_comparison.png", dpi=180)
print("Figure 13 saved in", figure_folder)
plt.show()
